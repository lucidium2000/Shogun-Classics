"""Write web/namefont.h: a small bold pixel font (DejaVu Sans Bold 9px, no
anti-aliasing) for the fighter names under the life bars."""
from PIL import Image, ImageDraw, ImageFont
f = ImageFont.truetype('/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf', 9)
H = 10
rows, widths = [], []
for c in range(32, 127):
    ch = chr(c)
    w = max(1, int(round(f.getlength(ch))))
    im = Image.new('L', (w + 2, 14), 0)
    d = ImageDraw.Draw(im); d.fontmode = '1'
    d.text((0, 0), ch, font=f, fill=255)
    px = im.load()
    r = []
    for y in range(H):
        m = 0
        for x in range(min(w + 1, 16)):
            if px[x, y + 1] > 128: m |= 1 << x
        r.append(m)
    rows.append(r); widths.append(w if c != 32 else 3)
out = ['/* generated by tools/gen_namefont.py */', '#define NF_H %d' % H,
       'static const unsigned char nf_w[95] = {%s};' % ','.join(map(str, widths)),
       'static const unsigned short nf_rows[95][%d] = {' % H]
out += ['  {%s},' % ','.join(map(str, r)) for r in rows]
out.append('};')
open('/home/claude/k91/web/namefont.h', 'w').write('\n'.join(out) + '\n')
print('ok')
